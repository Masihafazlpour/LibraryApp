begin;

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique check (username ~ '^[a-z0-9._-]{3,50}$'),
  full_name text not null check (char_length(trim(full_name)) between 2 and 120),
  role text not null default 'librarian' check (role in ('admin', 'librarian')),
  active boolean not null default true,
  created_by uuid null references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  last_login_at timestamptz null
);

create table if not exists public.library_settings (
  id smallint primary key default 1 check (id = 1),
  library_name text not null default 'کتابخانه دبیرستان شهید شیر آقائی',
  loan_days_default integer not null default 10 check (loan_days_default between 1 and 365),
  max_books_per_member integer not null default 3 check (max_books_per_member between 1 and 50),
  max_renewals_per_loan integer not null default 2 check (max_renewals_per_loan between 0 and 20),
  renew_days_per_extend integer not null default 7 check (renew_days_per_extend between 1 and 365),
  grades text[] not null default array['دهم','یازدهم','دوازدهم','پایه','یازدهم - دوازدهم','جامع'],
  fields text[] not null default array['تجربی','ریاضی','انسانی','جامع'],
  default_theme text not null default 'light' check (default_theme in ('light','dark')),
  logo_data text null,
  updated_by uuid null references public.profiles(id) on delete set null,
  updated_at timestamptz not null default now()
);

insert into public.library_settings (id) values (1)
on conflict (id) do nothing;

create table if not exists public.members (
  id bigint generated by default as identity primary key,
  membership_code text not null unique check (char_length(trim(membership_code)) between 1 and 30),
  first_name text not null check (char_length(trim(first_name)) between 1 and 80),
  last_name text not null check (char_length(trim(last_name)) between 1 and 100),
  phone text not null check (char_length(trim(phone)) between 3 and 20),
  national_code text null,
  grade text null,
  field text null,
  commitment boolean not null default true,
  photo_data text null check (photo_data is null or photo_data like 'data:image/%'),
  registered_at timestamptz not null default now(),
  created_by uuid not null references public.profiles(id) on delete restrict,
  updated_at timestamptz not null default now()
);

create index if not exists idx_members_name on public.members(last_name, first_name);
create index if not exists idx_members_phone on public.members(phone);
create index if not exists idx_members_national_code on public.members(national_code);

create table if not exists public.books (
  id bigint generated by default as identity primary key,
  reg_number text not null unique check (char_length(trim(reg_number)) between 1 and 30),
  title text not null check (char_length(trim(title)) between 1 and 250),
  abbr text null,
  grade text null,
  field text null,
  total integer not null default 1 check (total between 1 and 100000),
  available integer not null default 1 check (available >= 0 and available <= total),
  created_by uuid not null references public.profiles(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_books_title on public.books(title);
create index if not exists idx_books_available on public.books(available);

create table if not exists public.loans (
  id bigint generated by default as identity primary key,
  member_id bigint not null references public.members(id) on update cascade on delete restrict,
  book_id bigint not null references public.books(id) on update cascade on delete restrict,
  issue_at timestamptz not null default now(),
  due_at timestamptz not null,
  returned_at timestamptz null,
  renew_count integer not null default 0 check (renew_count >= 0),
  last_renewed_at timestamptz null,
  created_by uuid not null references public.profiles(id) on delete restrict,
  returned_by uuid null references public.profiles(id) on delete restrict,
  updated_at timestamptz not null default now(),
  check (due_at >= issue_at),
  check (returned_at is null or returned_at >= issue_at)
);

create index if not exists idx_loans_member on public.loans(member_id);
create index if not exists idx_loans_book on public.loans(book_id);
create index if not exists idx_loans_due_active on public.loans(due_at) where returned_at is null;
create unique index if not exists uq_active_member_book
  on public.loans(member_id, book_id)
  where returned_at is null;

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid null references public.profiles(id) on delete set null,
  action text not null,
  entity_type text not null,
  entity_id text null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists idx_audit_created_at on public.audit_logs(created_at desc);
create index if not exists idx_audit_actor on public.audit_logs(actor_id);

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

