create or replace function public.mark_login()
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then raise exception 'نشست معتبر نیست'; end if;
  update public.profiles set last_login_at = now() where id = auth.uid() and active = true;
end;
$$;

create or replace function public.issue_loan(p_member_id bigint, p_book_id bigint)
returns public.loans
language plpgsql
security definer
set search_path = public
as $$
declare
  v_settings public.library_settings%rowtype;
  v_book public.books%rowtype;
  v_active_count integer;
  v_loan public.loans%rowtype;
begin
  if not public.is_active_user() then raise exception 'دسترسی کاربر معتبر نیست'; end if;

  select * into v_settings from public.library_settings where id = 1;
  perform 1 from public.members where id = p_member_id;
  if not found then raise exception 'عضو یافت نشد'; end if;

  select * into v_book from public.books where id = p_book_id for update;
  if not found then raise exception 'کتاب یافت نشد'; end if;
  if v_book.available <= 0 then raise exception 'این کتاب موجود نیست'; end if;

  select count(*) into v_active_count
  from public.loans
  where member_id = p_member_id and returned_at is null;

  if v_active_count >= v_settings.max_books_per_member then
    raise exception 'حداکثر تعداد امانت این عضو تکمیل شده است';
  end if;

  if exists(select 1 from public.loans where member_id = p_member_id and book_id = p_book_id and returned_at is null) then
    raise exception 'این عضو همین کتاب را در امانت فعال دارد';
  end if;

  insert into public.loans(member_id, book_id, issue_at, due_at, created_by)
  values (p_member_id, p_book_id, now(), now() + make_interval(days => v_settings.loan_days_default), auth.uid())
  returning * into v_loan;

  update public.books set available = available - 1 where id = p_book_id;
  perform public.write_audit('issue', 'loan', v_loan.id::text, jsonb_build_object('member_id', p_member_id, 'book_id', p_book_id));
  return v_loan;
end;
$$;

create or replace function public.return_loan(p_loan_id bigint)
returns public.loans
language plpgsql
security definer
set search_path = public
as $$
declare
  v_loan public.loans%rowtype;
begin
  if not public.is_active_user() then raise exception 'دسترسی کاربر معتبر نیست'; end if;
  select * into v_loan from public.loans where id = p_loan_id for update;
  if not found then raise exception 'امانت یافت نشد'; end if;
  if v_loan.returned_at is not null then return v_loan; end if;

  update public.loans
  set returned_at = now(), returned_by = auth.uid()
  where id = p_loan_id
  returning * into v_loan;

  update public.books set available = least(total, available + 1) where id = v_loan.book_id;
  perform public.write_audit('return', 'loan', p_loan_id::text, jsonb_build_object('book_id', v_loan.book_id));
  return v_loan;
end;
$$;

create or replace function public.renew_loan(p_loan_id bigint)
returns public.loans
language plpgsql
security definer
set search_path = public
as $$
declare
  v_loan public.loans%rowtype;
  v_settings public.library_settings%rowtype;
begin
  if not public.is_active_user() then raise exception 'دسترسی کاربر معتبر نیست'; end if;
  select * into v_settings from public.library_settings where id = 1;
  select * into v_loan from public.loans where id = p_loan_id for update;
  if not found then raise exception 'امانت یافت نشد'; end if;
  if v_loan.returned_at is not null then raise exception 'امانت بازگشت داده شده است'; end if;
  if v_loan.renew_count >= v_settings.max_renewals_per_loan then raise exception 'حداکثر دفعات تمدید تکمیل شده است'; end if;

  update public.loans
  set due_at = greatest(due_at, now()) + make_interval(days => v_settings.renew_days_per_extend),
      renew_count = renew_count + 1,
      last_renewed_at = now()
  where id = p_loan_id
  returning * into v_loan;

  perform public.write_audit('renew', 'loan', p_loan_id::text, jsonb_build_object('renew_count', v_loan.renew_count, 'due_at', v_loan.due_at));
  return v_loan;
end;
$$;

create or replace function public.delete_loan(p_loan_id bigint)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_loan public.loans%rowtype;
begin
  if not public.is_active_user() then raise exception 'دسترسی کاربر معتبر نیست'; end if;
  select * into v_loan from public.loans where id = p_loan_id for update;
  if not found then raise exception 'امانت یافت نشد'; end if;

  if v_loan.returned_at is null then
    update public.books set available = least(total, available + 1) where id = v_loan.book_id;
  end if;
  delete from public.loans where id = p_loan_id;
  perform public.write_audit('delete', 'loan', p_loan_id::text, jsonb_build_object('member_id', v_loan.member_id, 'book_id', v_loan.book_id));
  return true;
end;
$$;

create or replace function public.update_book_inventory(p_book_id bigint, p_payload jsonb)
returns public.books
language plpgsql
security definer
set search_path = public
as $$
declare
  v_book public.books%rowtype;
  v_new_total integer;
  v_borrowed integer;
begin
  if not public.is_active_user() then raise exception 'دسترسی کاربر معتبر نیست'; end if;
  select * into v_book from public.books where id = p_book_id for update;
  if not found then raise exception 'کتاب یافت نشد'; end if;

  v_new_total := (p_payload->>'total')::integer;
  if v_new_total < 1 or v_new_total > 100000 then raise exception 'تعداد کل نامعتبر است'; end if;
  v_borrowed := v_book.total - v_book.available;
  if v_new_total < v_borrowed then
    raise exception 'تعداد کل نمی‌تواند از تعداد نسخه‌های در امانت کمتر باشد';
  end if;

  update public.books set
    reg_number = trim(p_payload->>'reg_number'),
    title = trim(p_payload->>'title'),
    abbr = nullif(trim(p_payload->>'abbr'), ''),
    grade = nullif(trim(p_payload->>'grade'), ''),
    field = nullif(trim(p_payload->>'field'), ''),
    total = v_new_total,
    available = v_new_total - v_borrowed
  where id = p_book_id
  returning * into v_book;

  perform public.write_audit('update', 'book', p_book_id::text, jsonb_build_object('total', v_new_total, 'available', v_book.available));
  return v_book;
end;
$$;

create or replace function public.restore_backup(p_backup jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_item jsonb;
  v_settings jsonb;
  v_members_count integer := 0;
  v_books_count integer := 0;
  v_loans_count integer := 0;
begin
  if not public.is_admin() then raise exception 'فقط مدیر سامانه اجازه بازیابی دارد'; end if;
  if coalesce((p_backup->>'version')::integer, 0) <> 2 then raise exception 'نسخه پشتیبان معتبر نیست'; end if;
  if jsonb_typeof(p_backup->'members') <> 'array' or jsonb_typeof(p_backup->'books') <> 'array' or jsonb_typeof(p_backup->'loans') <> 'array' then
    raise exception 'ساختار پشتیبان معتبر نیست';
  end if;

  delete from public.loans;
  delete from public.members;
  delete from public.books;

  for v_item in select value from jsonb_array_elements(p_backup->'members') loop
    insert into public.members(id, membership_code, first_name, last_name, phone, national_code, grade, field, commitment, photo_data, registered_at, created_by, updated_at)
    values (
      (v_item->>'id')::bigint, trim(v_item->>'membership_code'), trim(v_item->>'first_name'), trim(v_item->>'last_name'),
      trim(v_item->>'phone'), nullif(v_item->>'national_code',''), nullif(v_item->>'grade',''), nullif(v_item->>'field',''),
      coalesce((v_item->>'commitment')::boolean, true), nullif(v_item->>'photo_data',''),
      coalesce((v_item->>'registered_at')::timestamptz, now()), auth.uid(), now()
    );
    v_members_count := v_members_count + 1;
  end loop;

  for v_item in select value from jsonb_array_elements(p_backup->'books') loop
    insert into public.books(id, reg_number, title, abbr, grade, field, total, available, created_by, created_at, updated_at)
    values (
      (v_item->>'id')::bigint, trim(v_item->>'reg_number'), trim(v_item->>'title'), nullif(v_item->>'abbr',''),
      nullif(v_item->>'grade',''), nullif(v_item->>'field',''), greatest(1,(v_item->>'total')::integer),
      greatest(0, least((v_item->>'total')::integer, (v_item->>'available')::integer)), auth.uid(),
      coalesce((v_item->>'created_at')::timestamptz, now()), now()
    );
    v_books_count := v_books_count + 1;
  end loop;

  for v_item in select value from jsonb_array_elements(p_backup->'loans') loop
    insert into public.loans(id, member_id, book_id, issue_at, due_at, returned_at, renew_count, last_renewed_at, created_by, returned_by, updated_at)
    values (
      (v_item->>'id')::bigint, (v_item->>'member_id')::bigint, (v_item->>'book_id')::bigint,
      (v_item->>'issue_at')::timestamptz, (v_item->>'due_at')::timestamptz,
      nullif(v_item->>'returned_at','')::timestamptz, coalesce((v_item->>'renew_count')::integer,0),
      nullif(v_item->>'last_renewed_at','')::timestamptz, auth.uid(),
      case when nullif(v_item->>'returned_at','') is null then null else auth.uid() end, now()
    );
    v_loans_count := v_loans_count + 1;
  end loop;

  v_settings := p_backup->'library_settings';
  if jsonb_typeof(v_settings) = 'object' then
    update public.library_settings set
      library_name = coalesce(nullif(v_settings->>'library_name',''), library_name),
      loan_days_default = coalesce((v_settings->>'loan_days_default')::integer, loan_days_default),
      max_books_per_member = coalesce((v_settings->>'max_books_per_member')::integer, max_books_per_member),
      max_renewals_per_loan = coalesce((v_settings->>'max_renewals_per_loan')::integer, max_renewals_per_loan),
      renew_days_per_extend = coalesce((v_settings->>'renew_days_per_extend')::integer, renew_days_per_extend),
      grades = coalesce(array(select jsonb_array_elements_text(v_settings->'grades')), grades),
      fields = coalesce(array(select jsonb_array_elements_text(v_settings->'fields')), fields),
      logo_data = nullif(v_settings->>'logo_data',''),
      updated_by = auth.uid(), updated_at = now()
    where id = 1;
  end if;

  perform setval(pg_get_serial_sequence('public.members','id'), greatest(coalesce((select max(id) from public.members),1),1), true);
  perform setval(pg_get_serial_sequence('public.books','id'), greatest(coalesce((select max(id) from public.books),1),1), true);
  perform setval(pg_get_serial_sequence('public.loans','id'), greatest(coalesce((select max(id) from public.loans),1),1), true);

  perform public.write_audit('restore', 'backup', null, jsonb_build_object('members', v_members_count, 'books', v_books_count, 'loans', v_loans_count));
  return jsonb_build_object('ok', true, 'members', v_members_count, 'books', v_books_count, 'loans', v_loans_count);
end;
$$;

